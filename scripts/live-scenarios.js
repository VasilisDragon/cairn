export const LIVE_SCENARIOS = Object.freeze(LIVE_SCENARIO_DEFINITIONS.map((scenario) => Object.freeze({
  account: REGIME_A_ACCOUNT,
  ...scenario,
})));

export function getLiveScenario(id = DEFAULT_LIVE_SCENARIO_ID) {
  return LIVE_SCENARIOS.find((scenario) => scenario.id === id) || null;
}

export function runnableLiveScenarioIds() {
  return LIVE_SCENARIOS
    .filter((scenario) => scenario.requiresDeepSeek !== true)
    .map((scenario) => scenario.id);
}

export function primaryLiveScenarioIds() {
  return LIVE_SCENARIOS
    .filter((scenario) => /^[A-K]$/.test(String(scenario.order)))
    .map((scenario) => scenario.id);
}

export function liveScenarioSummary() {
  return LIVE_SCENARIOS
    .map((scenario) => {
      const setup = scenario.manualStateSetup ? 'manual setup' : 'scripted plan';
      const account = scenario.account?.label || 'account regime unspecified';
      return `${scenario.id} (${scenario.order}, ${setup}, ${account}): ${scenario.title}`;
    })
    .join('; ');
}
